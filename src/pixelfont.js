/** Columns between glyphs, and extra columns a space adds. */
export const GAP = 1
export const SPACE = 2

/**
 * Lays out `text` as pixels: [col, row] cells (row 0 at the top) and the total column count.
 * @returns {{ cells: [number, number][], cols: number, text: string }}
 */
export function pixelText(text) {
  const cells = []
  let col = 0
  let shown = ''
  for (const ch of text.toUpperCase()) {
    if (ch === ' ') {
      if (shown && !shown.endsWith(' ')) {
        col += SPACE
        shown += ' '
      }
      continue
    }
    const g = GLYPHS[ch]
    if (!g) continue
    if (shown && !shown.endsWith(' ')) col += GAP
    else if (shown.endsWith(' ')) col += GAP
    g.forEach((row, r) => [...row].forEach((c, k) => c === '#' && cells.push([col + k, r])))
    col += g[0].length
    shown += ch
  }
  return { cells, cols: col, text: shown.trimEnd() }
}
